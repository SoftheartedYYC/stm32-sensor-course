/**
 * @file    photo_app.h
 * @brief   光敏电阻传感器驱动接口
 *
 * 接线（本工程约定）：
 *   AO（模拟量输出） -> PA5   ADC1_IN5，0~3.3V 连续电压
 *   DO（数字量输出） -> PB0   上拉输入，读比较器输出（保留接口，不参与 LED 控制）
 *   VCC -> 3V3，GND -> GND
 *
 * DO 和 AO 的关系：
 *   模块上是一个"光敏电阻 + 电位器"分压，两路电压送进 LM393 比较器：
 *   AO 是分压点的原始电压；DO 是比较器把 AO 和电位器设定的门槛比出来的结果。
 *   AO 能看出光照的连续变化，DO 只能看出过没过门槛。
 *
 * 本工程为什么用 AO 而不是 DO 控制 LED：
 *   DO 的门槛由模块上的蓝色电位器决定，代码改不了；AO 是连续电压，
 *   换算成 0~100 的分值后，判"暗"的门槛写在下面的 PHOTO_DARK_SCORE 里，
 *   想改"多暗才点亮"只改一个宏，还能把分值同时显示在 OLED 上。
 *   DO 的读取函数仍然保留，方便接线排错或以后改回开关量方案。
 */

#ifndef __PHOTO_APP_H /* 头文件保护宏 */
#define __PHOTO_APP_H

#include "stm32f10x.h" /* 标准外设库：uint8_t / GPIO / ADC */

/* ------------------------------------------------------------------
 * 接线：换引脚只改这里（端口、引脚、端口时钟、ADC 通道要一起改）
 *
 * 例：AO 从 PA5 换到 PC0（ADC1_IN10）：
 *   PHOTO_AO_PORT    -> GPIOC
 *   PHOTO_AO_PIN     -> GPIO_Pin_0
 *   PHOTO_AO_RCC     -> RCC_APB2Periph_GPIOC
 *   PHOTO_AO_CHANNEL -> ADC_Channel_10
 * ------------------------------------------------------------------ */
#define PHOTO_DO_PORT    GPIOB                  /* DO 所在端口 */
#define PHOTO_DO_PIN     GPIO_Pin_0             /* DO = PB0 */
#define PHOTO_DO_RCC     RCC_APB2Periph_GPIOB   /* DO 端口的时钟 */
#define PHOTO_AO_PORT    GPIOA                  /* AO 所在端口 */
#define PHOTO_AO_PIN     GPIO_Pin_5             /* AO = PA5 */
#define PHOTO_AO_RCC     RCC_APB2Periph_GPIOA   /* AO 端口的时钟 */
#define PHOTO_AO_CHANNEL ADC_Channel_5          /* PA5 对应的 ADC 通道 = 通道 5 */

/* ------------------------------------------------------------------
 * DO 的极性
 *   本模块实测：光照越强 -> 光敏电阻阻值越小 -> 分压点电压越低，
 *   比较器输出 DO = 1 表示"暗"、0 表示"亮"。
 *   如果你的模块刚好相反（遮住光时 DO 变成 0），把下面这个宏改成 0 即可；
 *   它只影响保留的 photo_is_dark()，不再影响 LED（LED 走 AO 的 PHOTO_DARK_SCORE）。
 * ------------------------------------------------------------------ */
#define PHOTO_DO_DARK_LEVEL 1 /* DO 等于该电平时判定为"暗" */

/* ------------------------------------------------------------------
 * 分值方向
 *   把 AO 的 0~4095 线性映射成 0~100 的"光照分值"：
 *       分值 = (4095 - raw) * 100 / 4095
 *   本模块实测"越亮 AO 电压越低"（光敏电阻在分压下臂），所以这里取 1，
 *   先把 raw 翻过来，保证屏幕上是"越亮分值越大"。
 *   如果你的模块是"越亮 AO 越高"，把下面这个宏改成 0 即可，
 *   分值和报警阈值的方向会一起反过来，其它代码不用动。
 * ------------------------------------------------------------------ */
#define PHOTO_SCORE_INVERT 1

/* ------------------------------------------------------------------
 * 明暗判定（AO 分值）
 *   分值 0 = 最暗，100 = 最亮。分值低于"当前光敏阈值"判"暗"（D0 点亮）；
 *   要回到 阈值 + PHOTO_DARK_HYST 以上才判回"亮"。
 *   阈值由主程序传入（默认 PHOTO_DARK_SCORE = 30，可用按键调整）；
 *   回差固定 3 分，避免分值在门槛附近抖动时 LED 一闪一闪。
 * ------------------------------------------------------------------ */
#define PHOTO_DARK_SCORE 30 /* 默认光敏阈值：分值低于它判"暗" */
#define PHOTO_DARK_HYST  3  /* 回差：分值 >= 阈值+3 才转回"亮" */

/* ------------------------------------------------------------------
 * 对外接口
 * ------------------------------------------------------------------ */

/* 初始化 PA5（模拟输入，读 AO）、PB0（上拉输入，读 DO）并校准 ADC1 */
void photo_init(void);

/* ------------------------------------------------------------------
 * DO（数字量）—— 保留接口，主程序不再调用
 *   LED 的明暗现在由 AO 分值判断（photo_score_is_dark），下面三个函数
 *   留作接线调试或备用；它们读的是 PB0，不是 LED 的判定来源。
 * ------------------------------------------------------------------ */

/* 读 DO 引脚的原始电平（0/1）—— 不做任何滤波，调试接线时用它 */
uint8_t photo_do_raw(void);

/* 读 DO 并做 5 取 3 多数表决 —— 比较器在门槛附近会抖动，表决后显示才不会跳 */
uint8_t photo_do_get(void);

/* 把 DO 电平翻译成"当前是否偏暗"：返回 1 = 暗，0 = 亮（保留接口） */
uint8_t photo_is_dark(void);

/* 启动一次 ADC 转换并返回结果，范围 0~4095（12 位） */
uint16_t photo_ao_raw(void);

/* 连续采样 times 次求平均，压低随机噪声；times 传 0 按 1 次处理 */
uint16_t photo_ao_avg(uint8_t times);

/* 把 AO 的原始值换算成毫伏：0~3300 mV（按 VREF = 3.3V 算）。
 * 做成"传入 raw"的纯换算函数，是为了让主循环能把电压算在"平均之后"的值上 ——
 * 否则想显示电压就得再单独采一次，显示的电压和显示的原始值对不上。 */
uint16_t photo_raw_to_mv(uint16_t raw);

/* 把 AO 的原始值换算成 0~100 的光照分值（先乘后除，四舍五入）。
 * 主循环拿它和阈值比较，超过就报警；同时用它判断明暗、控制 D0。 */
uint8_t photo_score(uint16_t raw);

/* 用 AO 分值判断当前是否偏暗（带 PHOTO_DARK_HYST 回差）。
 * dark_score 是当前暗阈值，由主程序传入，所以可以用按键调整。
 * 返回 1 = 暗，0 = 亮。主循环每拍传最新分值和当前阈值即可。 */
uint8_t photo_score_is_dark(uint8_t score, uint8_t dark_score);

#endif /* __PHOTO_APP_H */
